"""``stataudit init``: set a repository up for stataudit on pull requests in one step.

Writes small *caller* workflows that delegate to the reusable workflows in the
stataudit repository, plus a commented ``stataudit.toml``:

* ``.github/workflows/stataudit.yml``         -- checks (``pull_request``, unprivileged)
* ``.github/workflows/stataudit-comment.yml`` -- posts the card (``workflow_run``, never runs PR code)
* ``.github/workflows/stataudit-agent.yml``   -- with ``--agent``: experimental verified fixes
* ``stataudit.toml``

Existing files are never overwritten unless ``force`` is set; without it,
nothing at all is written when any target exists.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path

from . import __version__

__all__ = ["InitError", "InitResult", "init_repo", "check_caller", "comment_caller", "agent_caller", "config_template",
           "TOOL_REPOSITORY", "DEFAULT_REF", "CHECK_PATH", "COMMENT_PATH", "AGENT_PATH", "CONFIG_PATH"]

TOOL_REPOSITORY = "bhaskargurram-ai/stataudit"
DEFAULT_REF = f"v{__version__}"
_REF_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._/-]{0,99}$")

CHECK_PATH = ".github/workflows/stataudit.yml"
COMMENT_PATH = ".github/workflows/stataudit-comment.yml"
AGENT_PATH = ".github/workflows/stataudit-agent.yml"
CONFIG_PATH = "stataudit.toml"


class InitError(RuntimeError):
    """``init`` cannot proceed (existing files, bad ref)."""


@dataclass
class InitResult:
    install_command: str
    written: list[str] = field(default_factory=list)
    next_steps: list[str] = field(default_factory=list)


def detect_install(repo: Path) -> str:
    """The command that installs the analyses' dependencies (it runs PR code, in the unprivileged job)."""
    if (repo / "requirements.txt").is_file():
        return "pip install -r requirements.txt"
    if (repo / "pyproject.toml").is_file() or (repo / "setup.py").is_file():
        return "pip install -e ."
    return ""


def _yaml_str(s: str) -> str:
    return f"'{s}'" if "'" not in s else json.dumps(s)


def check_caller(ref: str, install: str = "") -> str:
    prefix = f"{TOOL_REPOSITORY}/.github/workflows"
    return f"""# stataudit, part 1 of 2: check the pull request (UNPRIVILEGED).
#
# Runs on `pull_request`, so for pull requests from forks GitHub gives this
# workflow a read-only token and no secrets. It lints changed .py/.ipynb files,
# recomputes the p-values in changed reports, and re-runs the analyses listed
# under `run` in stataudit.toml (that executes PR code, here only). The card
# goes to the job summary and into the `stataudit-result` artifact;
# stataudit-comment.yml posts it on the pull request.
#
# Generated by `stataudit init`. Pin the reusable workflow to a release tag
# or, stricter, to a full commit SHA, and keep `stataudit-ref` the same.
name: stataudit

on:
  pull_request:
    types: [opened, synchronize, reopened]

permissions:
  contents: read

concurrency:
  group: stataudit-${{{{ github.event.pull_request.number }}}}
  cancel-in-progress: true

jobs:
  check:
    uses: {prefix}/check.yml@{ref}
    with:
      stataudit-ref: {ref}
      python-version: "3.12"
      # Installs what the analyses import (runs PR code, unprivileged job). numpy, scipy
      # and pandas are already there.
      install-command: {_yaml_str(install)}
      fail-on: never   # or "warn" / "fail" to fail the check
"""


def comment_caller(ref: str) -> str:
    prefix = f"{TOOL_REPOSITORY}/.github/workflows"
    return f"""# stataudit, part 2 of 2: post the card (PRIVILEGED, never runs PR code).
#
# Triggered when the `stataudit` workflow completes. `workflow_run` runs with a
# token that can comment, so the reusable workflow never checks out, installs
# or executes anything from the pull request: it downloads the result
# artifact, validates it, re-renders the card, upserts one comment and sets a
# `stataudit: pass|warnings|problems` label. Do not use `pull_request_target`.
#
# Generated by `stataudit init`.
name: stataudit comment

on:
  workflow_run:
    workflows: ["stataudit"]   # must match the `name:` of stataudit.yml
    types: [completed]

permissions: {{}}

jobs:
  comment:
    if: github.event.workflow_run.event == 'pull_request' && github.event.workflow_run.conclusion != 'cancelled'
    permissions:
      contents: read
      actions: read          # download the artifact of the triggering run
      pull-requests: write   # upsert the comment and the label
    uses: {prefix}/comment.yml@{ref}
    with:
      stataudit-ref: {ref}
      labels: true
"""


def agent_caller(ref: str, install: str = "") -> str:
    prefix = f"{TOOL_REPOSITORY}/.github/workflows"
    return f"""# stataudit agent: verified fixes (EXPERIMENTAL, opt-in).
#
# When the check finds an analysis whose conclusion is fragile or does not
# hold, an LLM proposes a corrected analysis and stataudit re-runs it to
# verify it. The work is split over separate jobs (separate VMs):
#   gate    - decides whether to run; reads the API only, runs no PR code
#   propose - holds the LLM key; reads the PR as data, never installs or runs it
#   verify  - runs the original and the candidate analyses; no secrets, read-only token
#   comment - re-posts the card with the agent section; never runs PR code
#
# Setup: repository secret STATAUDIT_LLM_API_KEY, repository variables
# STATAUDIT_LLM_PROVIDER (anthropic | openai) and STATAUDIT_LLM_MODEL
# (optional: STATAUDIT_LLM_BASE_URL, and STATAUDIT_LLM_REASONING_EFFORT = none
# for OpenAI GPT-6 Luna). [agent] enabled = true must be set in stataudit.toml
# on the default branch. By default the agent only runs for pull requests by
# owners, members and collaborators, or labelled `stataudit:agent`.
#
# Generated by `stataudit init --agent`.
name: stataudit agent

on:
  workflow_run:
    workflows: ["stataudit"]   # must match the `name:` of stataudit.yml
    types: [completed]

permissions: {{}}

jobs:
  agent:
    if: github.event.workflow_run.event == 'pull_request' && github.event.workflow_run.conclusion != 'cancelled'
    permissions:
      contents: read
      actions: read
      pull-requests: read
    uses: {prefix}/agent.yml@{ref}
    with:
      stataudit-ref: {ref}
      llm-provider: ${{{{ vars.STATAUDIT_LLM_PROVIDER }}}}
      llm-model: ${{{{ vars.STATAUDIT_LLM_MODEL }}}}
      llm-base-url: ${{{{ vars.STATAUDIT_LLM_BASE_URL }}}}
      llm-reasoning-effort: ${{{{ vars.STATAUDIT_LLM_REASONING_EFFORT }}}}
      python-version: "3.12"
      install-command: {_yaml_str(install)}
      run-for: trusted   # or "everyone" (spends API credits on any fork PR)
    secrets:
      llm-api-key: ${{{{ secrets.STATAUDIT_LLM_API_KEY }}}}

  comment:
    needs: agent
    if: needs.agent.outputs.verified == 'true'
    permissions:
      contents: read
      actions: read
      pull-requests: write
    uses: {prefix}/comment.yml@{ref}
    with:
      stataudit-ref: {ref}
      # Trusted values: the PR number comes from the gate job (API data, no PR
      # code ran there) and the artifact from this run's verify job.
      pr-number: ${{{{ needs.agent.outputs.pr-number }}}}
      artifact-run-id: ${{{{ github.run_id }}}}
      labels: true
"""


def config_template(agent: bool = False) -> str:
    text = f"""# stataudit configuration (https://github.com/{TOOL_REPOSITORY}).
#
# In CI this file is read from the pull request's BASE commit, so a pull
# request cannot weaken its own check. Every key is optional.

alpha = 0.05
fail_on = "fail"                    # never | warn | fail: when `stataudit ci` exits non-zero

# Analyses re-run under the tracer on every pull request (this EXECUTES them, in
# the unprivileged job). Opt-in: list the scripts and notebooks to run.
run = ["analysis/**/*.py"]

# Reports whose APA-style results (t(28) = 2.20, p = .036, ...) are recomputed when they change.
reports = ["reports/**/*.md"]

# lint = ["**/*.py", "**/*.ipynb"]  # statically checked when they change
# lint_ignore = ["SA107"]
# timeout = 300                     # seconds per analysis
# max_files = 50

# [agent]                           # verified fixes (stataudit-agent.yml); experimental
# enabled = false
# max_fixes = 3                     # analyses per pull request
# max_tool_calls = 12
# share_data = false                # never send raw data rows to the LLM unless true

# [llm]                             # the key only comes from STATAUDIT_LLM_API_KEY
# provider = "anthropic"            # or "openai" for any OpenAI-compatible endpoint
# model = ""
"""
    if agent:
        text = text.replace("# [agent]  ", "[agent]    ", 1).replace("# enabled = false\n", "enabled = true\n", 1)
    return text


def init_repo(repo: str | Path = ".", agent: bool = False, force: bool = False, ref: str | None = None,
              install_command: str | None = None) -> InitResult:
    """Write the caller workflows and the config into ``repo``."""
    root = Path(repo)
    if not root.is_dir():
        raise InitError(f"not a directory: {root}")
    ref = ref or DEFAULT_REF
    if not _REF_RE.match(ref) or ".." in ref:
        raise InitError(f"invalid --ref {ref!r}: use a tag, branch or commit SHA")
    install = detect_install(root) if install_command is None else install_command
    if "\n" in install:
        raise InitError("--install-command must be a single line")
    files = {
        CHECK_PATH: check_caller(ref, install),
        COMMENT_PATH: comment_caller(ref),
        CONFIG_PATH: config_template(agent),
    }
    if agent:
        files[AGENT_PATH] = agent_caller(ref, install)
    existing = [p for p in files if (root / p).exists() or (root / p).is_symlink()]
    if existing and not force:
        raise InitError("refusing to overwrite existing file(s): " + ", ".join(existing) + " (use --force)")
    for rel, text in files.items():
        target = root / rel
        if target.is_symlink():
            target.unlink()
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
    res = InitResult(install_command=install, written=list(files))
    res.next_steps.append("Edit stataudit.toml: list the analyses to re-run under `run` and the reports to check "
                          "under `reports`.")
    res.next_steps.append("Review and commit the files: git add " + " ".join(files) + " && git commit -m 'Add stataudit'")
    res.next_steps.append("Merge them to the default branch: workflow_run workflows (the comment and agent "
                          "workflows) only run from the default branch.")
    if agent:
        res.next_steps.append("Add the LLM key as a repository secret: gh secret set STATAUDIT_LLM_API_KEY")
        res.next_steps.append("Set repository variables: gh variable set STATAUDIT_LLM_PROVIDER --body anthropic "
                              "(or openai) and gh variable set STATAUDIT_LLM_MODEL --body <model id> (optional: "
                              "STATAUDIT_LLM_BASE_URL; for OpenAI GPT-6 Luna also gh variable set "
                              "STATAUDIT_LLM_REASONING_EFFORT --body none)")
        res.next_steps.append("The agent runs for PRs by owners/members/collaborators, or when a maintainer adds the "
                              "`stataudit:agent` label; set run-for: everyone to change that.")
    res.next_steps.append("Open a pull request: the card appears in the job summary and as a PR comment.")
    return res
